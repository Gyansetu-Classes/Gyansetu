/**
 * Class 10 > Maths > Polynomials (ch-2) reuses one parabola diagram for both
 * of its "how many zeroes / where does it cross the x-axis" image questions
 * (Level 2 Q7 asks generically, Level 5 Q9 asks about this exact function).
 * y = x² – 2x – 8 = (x–4)(x+2): opens upward, crosses the x-axis at x=–2 and
 * x=4, vertex at (1, –9). No real photo was supplied for class-10, so this
 * is a generated placeholder in the same style as ch-1/ch-3/ch-5's other
 * diagrams — swap in a real image the same way ch-1's were, if one arrives.
 */
function parabolaImage() {
  const width = 460, height = 340;
  const originX = 175, originY = 176; // pixel position of (0,0)
  const scaleX = 45, scaleY = 13; // px per unit — independent x/y scale so the deep, wide curve still fits

  const toPx = (x, y) => [originX + x * scaleX, originY - y * scaleY];

  // y = x² - 2x - 8, sampled across x in [-3, 5.3] (numerically checked to
  // stay on-canvas at this scale — the vertex is deep at y=-9 while the arms
  // rise quickly, so this range and scale were chosen together, not guessed).
  const samples = [];
  for (let x = -3; x <= 5.3 + 1e-9; x += 0.1) {
    const y = x * x - 2 * x - 8;
    samples.push(toPx(x, y));
  }
  const curve = samples.map(([x, y], i) => `${i === 0 ? "M" : "L"} ${x.toFixed(1)} ${y.toFixed(1)}`).join(" ");

  const [axisLeftX] = toPx(-3.3, 0);
  const [axisRightX] = toPx(5.6, 0);
  const [, axisTopY] = toPx(0, 12);
  const [, axisBottomY] = toPx(0, -10.5);

  const [leftRootX, rootY] = toPx(-2, 0);
  const [rightRootX] = toPx(4, 0);
  const [vertexX, vertexY] = toPx(1, -9);

  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
      <rect width="${width}" height="${height}" fill="#F5FCEC" />
      <line x1="${axisLeftX}" y1="${originY}" x2="${axisRightX}" y2="${originY}" stroke="#171D14" stroke-width="2" />
      <line x1="${originX}" y1="${axisTopY}" x2="${originX}" y2="${axisBottomY}" stroke="#171D14" stroke-width="2" />
      <text x="${axisRightX}" y="${originY - 8}" font-size="14" fill="#40493D">x</text>
      <text x="${originX + 8}" y="${axisTopY + 6}" font-size="14" fill="#40493D">y</text>
      <path d="${curve}" fill="none" stroke="#0D631B" stroke-width="2.4" />
      <circle cx="${leftRootX}" cy="${rootY}" r="5" fill="#BA1A1A" />
      <text x="${leftRootX}" y="${rootY + 22}" font-size="13" font-weight="700" text-anchor="middle" fill="#BA1A1A">(–2, 0)</text>
      <circle cx="${rightRootX}" cy="${rootY}" r="5" fill="#BA1A1A" />
      <text x="${rightRootX}" y="${rootY + 22}" font-size="13" font-weight="700" text-anchor="middle" fill="#BA1A1A">(4, 0)</text>
      <circle cx="${vertexX}" cy="${vertexY}" r="5" fill="#825500" />
      <text x="${vertexX}" y="${vertexY + 24}" font-size="13" font-weight="700" text-anchor="middle" fill="#825500">(1, –9)</text>
      <text x="${width / 2}" y="24" font-size="14" text-anchor="middle" fill="#40493D">y = x² – 2x – 8</text>
    </svg>
  `.trim();

  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

