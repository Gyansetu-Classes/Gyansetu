/**
 * Q13, Level 4 of ch-5 (Euclid's Geometry) — a segment with four points A, B,
 * C, D in that order, with AC and BD each picked out by their own bracket
 * above/below the line, illustrating the proof that AC=BD implies AB=CD
 * (subtract the shared BC from both). No real photo was supplied for this
 * one (unlike ch-1/ch-3's image questions), so this is a generated
 * placeholder in the same style as those chapters' other diagrams — swap in
 * a real image the same way ch-1's were, whenever one is provided.
 */
function lineSegmentACBDImage() {
  const y = 150;
  const points = { A: 50, B: 160, C: 300, D: 410 };
  const left = 30, right = 430;

  const tick = (x, label) => `
    <line x1="${x}" y1="${y - 10}" x2="${x}" y2="${y + 10}" stroke="#171D14" stroke-width="2.4" />
    <circle cx="${x}" cy="${y}" r="4.5" fill="#171D14" />
    <text x="${x}" y="${y + 32}" font-size="16" font-weight="700" text-anchor="middle" fill="#171D14">${label}</text>
  `;

  // A bracket arcing above (or below) the line between two point x-positions.
  const bracket = (x1, x2, side, color, label) => {
    const midY = side === "up" ? y - 34 : y + 34;
    const endY = side === "up" ? y - 8 : y + 8;
    const labelY = side === "up" ? midY - 10 : midY + 22;
    return `
      <path d="M ${x1} ${endY} Q ${(x1 + x2) / 2} ${midY} ${x2} ${endY}" fill="none" stroke="${color}" stroke-width="2.4" />
      <text x="${(x1 + x2) / 2}" y="${labelY}" font-size="15" font-weight="700" text-anchor="middle" fill="${color}">${label}</text>
    `;
  };

  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" width="460" height="240" viewBox="0 0 460 240">
      <rect width="460" height="240" fill="#F5FCEC" />
      <text x="230" y="26" font-size="15" text-anchor="middle" fill="#40493D">If AC = BD, then AB = CD</text>
      <line x1="${left}" y1="${y}" x2="${right}" y2="${y}" stroke="#171D14" stroke-width="2.4" />
      ${bracket(points.A, points.C, "up", "#0D631B", "AC")}
      ${bracket(points.B, points.D, "down", "#825500", "BD")}
      ${Object.entries(points).map(([label, x]) => tick(x, label)).join("")}
    </svg>
  `.trim();

  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

